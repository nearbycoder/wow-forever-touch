-- Loads the real addon in the mock client and exports the on-screen rectangle of
-- every HUD control, per screen profile, for the README preview renderer.
-- Run from the repo root:  lua5.1 tools/preview/export_layout.lua > tools/preview/layout.js
package.path = "./tests/?.lua;" .. package.path
local M = require("mock_wow")
M.install()
local ns = {}
M.LoadToc("ForeverTouch", "ForeverTouch", ns)

-- A warrior with a few things on the bars (icon keys are matched by the renderer).
local demo = { [1] = "sword", [2] = "strike", [3] = "rend", [4] = "shout", [5] = "charge", [6] = "shield",
    [7] = "potion", [8] = "bandage", [9] = "hamstring", [10] = "thunder", [11] = "hearth", [12] = "food" }
for slot, icon in pairs(demo) do M.actions[slot] = { texture = icon, kind = "spell", id = slot } end
M.actions[61] = { texture = "fire", kind = "spell", id = 61 }

M.FireEvent("ADDON_LOADED", "ForeverTouch")
M.FireEvent("PLAYER_LOGIN")
M.FireEvent("PLAYER_ENTERING_WORLD")

local function eff(f)
    local s = 1
    while f and f ~= M.UIParent do s = s * (f._scale or 1) f = f._parent end
    return s
end

local rect
local function pointXY(r, p)
    local x = p:find("LEFT") and r.l or (p:find("RIGHT") and r.l + r.w or r.l + r.w / 2)
    local y = p:find("BOTTOM") and r.b or (p:find("TOP") and r.b + r.h or r.b + r.h / 2)
    return x, y
end
function rect(f)
    if f == M.UIParent then return { l = 0, b = 0, w = f._w, h = f._h } end
    local s = eff(f)
    local w, h = (f._w or 0) * s, (f._h or 0) * s
    local p = f._points[1]
    if not p then return { l = 0, b = 0, w = w, h = h } end
    if p[1] == "ALL" then return rect(p[2] or f._parent) end
    local point, rel, relPoint, x, y = p[1], p[2], p[3], p[4], p[5]
    if type(rel) == "number" or rel == nil then -- SetPoint(point, x, y)
        x, y, rel, relPoint = rel or 0, relPoint or 0, f._parent, point
    end
    if type(rel) == "string" then rel = _G[rel] end
    local ax, ay = pointXY(rect(rel or f._parent), relPoint or point)
    ax, ay = ax + (x or 0) * s, ay + (y or 0) * s
    -- place f's own anchor point at (ax, ay)
    local l = point:find("LEFT") and ax or (point:find("RIGHT") and ax - w or ax - w / 2)
    local b = point:find("BOTTOM") and ay or (point:find("TOP") and ay - h or ay - h / 2)
    return { l = l, b = b, w = w, h = h }
end

local function encode(v)
    local t = type(v)
    if t == "table" then
        if #v > 0 or next(v) == nil then
            local out = {}
            for i = 1, #v do out[i] = encode(v[i]) end
            return "[" .. table.concat(out, ",") .. "]"
        end
        local keys, out = {}, {}
        for k in pairs(v) do keys[#keys + 1] = k end
        table.sort(keys)
        for _, k in ipairs(keys) do out[#out + 1] = string.format("%q:%s", k, encode(v[k])) end
        return "{" .. table.concat(out, ",") .. "}"
    elseif t == "string" then return string.format("%q", v)
    elseif t == "number" then return string.format("%.2f", v)
    elseif t == "boolean" then return tostring(v)
    end
    return "null"
end

local function snapshot()
    local items = {}
    local function add(kind, f, extra)
        local r = rect(f)
        local item = { kind = kind, x = r.l, y = r.b, w = r.w, h = r.h }
        for k, v in pairs(extra or {}) do item[k] = v end
        items[#items + 1] = item
    end
    for i = 1, 12 do
        local b = _G["ForeverTouchButton" .. i]
        local slot = b:GetAttribute("action")
        add("action", b, { index = i, slot = slot, icon = M.actions[slot] and M.actions[slot].texture or "" })
    end
    add("pill", _G.ForeverTouchPagePill, { text = _G.ForeverTouchPagePill.glyph:GetText() })
    local labels = { "Target", "Assist", "Clear" }
    for i = 1, 3 do add("utility", _G["ForeverTouchUtility" .. i], { label = labels[i], icon = labels[i]:lower() }) end
    local zoom = {}
    for _, c in ipairs(_G.ForeverTouchCamera._children) do if c._isFrame then zoom[#zoom + 1] = c end end
    add("zoom", zoom[1], { text = "+" })
    add("zoom", zoom[2], { text = "-" })
    add("menu", _G.ForeverTouchMenuButton)
    for name, f in pairs(ns.groups) do
        add("group", f, { name = name, label = ns.groupLabels[name] })
    end
    return { width = M.UIParent._w, height = M.UIParent._h, items = items, handed = ns.db.handed }
end

local out = {}
-- Folded: cover screen 2520x1080 -> UI 1792x768
out.cover = snapshot()
-- Unfolded: inner screen 2184x1968 -> UI 852x768
M.screen = { 2184, 1968 }
M.UIParent._w = math.floor(768 * 2184 / 1968)
M.FireEvent("DISPLAY_SIZE_CHANGED")
M.RunTimers(1)
out.main = snapshot()
-- Left-handed, folded
M.screen = { 2520, 1080 }
M.UIParent._w = 1792
M.FireEvent("DISPLAY_SIZE_CHANGED")
M.RunTimers(1)
ns.SetHanded("left")
out.coverLeft = snapshot()

io.write("// Generated by tools/preview/export_layout.lua from the real addon code.\nwindow.LAYOUT = ", encode(out), ";\n")
